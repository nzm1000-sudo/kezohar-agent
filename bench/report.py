"""Build a results page from bench/<raw dir>/*.json.

Usage: python3 bench/report.py [--raw raw] [--out results.md]
"""
import argparse, json, statistics
from pathlib import Path

BENCH = Path(__file__).resolve().parent
TARGET_TOTAL_S = 5.0
BUSY_LOADAVG = 3.0  # 1-min load average above this = measured under load

ap = argparse.ArgumentParser()
ap.add_argument("--raw", default="raw")
ap.add_argument("--out", default="results.md")
opt = ap.parse_args()
runs = [json.loads(p.read_text()) for p in sorted((BENCH / opt.raw).glob("*.json"))]


def condition(r):
    c = r.get("conditions") or {}
    if "note" in c:
        return "⚠️ " + c["note"]
    loads = [c[k]["loadavg_1m"] for k in ("start", "end") if k in c]
    peak = {}  # process name -> highest CPU% seen
    for k in ("start", "end"):
        for p in c.get(k, {}).get("busy_procs", []):
            name, _, pct = p.rpartition(" ")
            peak[name] = max(peak.get(name, 0), int(pct.rstrip("%")))
    procs = [f"{n} {v}%" for n, v in sorted(peak.items(), key=lambda kv: -kv[1])]
    busy = max(loads, default=0) > BUSY_LOADAVG
    return (("⚠️ under load" if busy else "idle") + f" — load avg {'/'.join(map(str, loads))}"
            + (f"; busy: {', '.join(procs)}" if procs else ""))


def med(xs):
    xs = [x for x in xs if x is not None]
    return round(statistics.median(xs), 2) if xs else None


def mx(xs):
    xs = [x for x in xs if x is not None]
    return round(max(xs), 2) if xs else None


lines = ["# Phase 0 — Model benchmark results", "",
         f"Generated by `bench/report.py` from `bench/{opt.raw}/*.json`. Mac M4 Pro 48 GB, LM Studio, context 8192, "
         "`reasoning_effort: none`, temperature 0.2. Answer test = question + fixed Shulchan Aruch passages "
         "(`bench/contexts.json`); [fast] questions are skipped there (they go to the code fast path).", "",
         "## Measurement conditions", "",
         "Times measured while other programs use the CPU/GPU are slower than on an idle Mac. "
         f"'Under load' = 1-minute load average above {BUSY_LOADAVG} (12 cores).", "",
         *[f"- **{r['model']}** — {condition(r)}" for r in runs], "",
         "## Summary", "",
         "| Model | Quant | File GB | Mem Δ GB | TTFT med (s) | 1st sentence med (s) | Total med (s) | Total max (s) "
         "| ≤5s answers | tok/s med | tokens med | sentences med | >5 sentences | tool-call ok | reasoning leaked |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
for r in runs:
    ans = [q["answer"] for q in r["questions"] if "answer" in q]
    tools = [q["tool"] for q in r["questions"] if q["tool"]["verdict"] != "n/a"]
    ld = r["load"]
    lines.append("| " + " | ".join(str(x) for x in [
        r["model"], ld["quant"], ld["file_gb"], ld["mem_delta_gb"],
        med([a["ttft_s"] for a in ans]), med([a["first_sentence_s"] for a in ans]),
        med([a["total_s"] for a in ans]), mx([a["total_s"] for a in ans]),
        f"{sum(a['total_s'] <= TARGET_TOTAL_S for a in ans)}/{len(ans)}",
        med([a["tok_per_s"] for a in ans]), med([a["completion_tokens"] for a in ans]),
        med([a["sentences"] for a in ans]), sum(a["sentences"] > 5 for a in ans),
        f"{sum(t['verdict'] == 'ok' for t in tools)}/{len(tools)}",
        sum(1 for a in ans if a["reasoning_tokens"] or a["reasoning_chars"]),
    ]) + " |")

notes = BENCH / "notes.md"
if opt.raw == "raw" and notes.exists():
    lines += ["", notes.read_text().strip()]

lines += ["", "## Tool-call test (dummy `search_halacha`)", "",
          "ok = called the tool with a Hebrew query for [src]/[both]/[nosrc], or did NOT call it for [refuse]. "
          "[fast] = n/a (answered by code).", "",
          "| # | Question | Tags | " + " | ".join(r["model"] for r in runs) + " |",
          "|---|---|---|" + "---|" * len(runs)]
for i, q in enumerate(runs[0]["questions"]):
    cells = []
    for r in runs:
        t = r["questions"][i]["tool"]
        arg = t["args"].get("query", "") if isinstance(t["args"], dict) else (t["args"] or "")
        cells.append(f"{t['verdict']}" + (f" «{arg}»" if arg else ""))
    lines.append(f"| {q['n']} | {q['q']} | {' '.join(q['tags'])} | " + " | ".join(cells) + " |")

lines += ["", "## Answers — for your review", "",
          "Not graded for halachic correctness. Columns: time to first token / total seconds, "
          "sentences, and mechanical checks (cites a given source / says 'אין לי מקור').", ""]
for i, q in enumerate(runs[0]["questions"]):
    if "answer" not in q:
        continue
    lines += [f"### {q['n']}. {q['q']} {' '.join('[' + t + ']' for t in q['tags'])}", ""]
    for r in runs:
        a = r["questions"][i]["answer"]
        flags = []
        if a["cites_given_source"]: flags.append("cites source")
        if a["says_no_source"]: flags.append("says no source")
        if a["latin_chars"]: flags.append(f"{a['latin_chars']} Latin chars")
        if a["reasoning_tokens"] or a["reasoning_chars"]: flags.append("reasoning leaked")
        lines += [f"**{r['model']}** — {a['ttft_s']}s / {a['total_s']}s, {a['sentences']} sentences"
                  + (f" — {', '.join(flags)}" if flags else ""), "",
                  "> " + (a["answer"] or "(empty)").replace("\n", "\n> "), ""]

(BENCH / opt.out).write_text("\n".join(lines) + "\n")
print("wrote", BENCH / opt.out)
