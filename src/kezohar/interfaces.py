"""Small boundaries between knowledge, retrieval, verification and inference."""
from typing import Protocol


class SearchEngine(Protocol):
    def search(self, query, top_k=5): ...


class AnswerModel(Protocol):
    @property
    def identity(self): ...
    def generate(self, question, sources, timeout=4.5): ...
    def health(self, timeout=8): ...


class KnowledgeEngine(Protocol):
    search: SearchEngine
    def upsert_verified(self, sources): ...
    def status(self): ...


class SourceVerifier(Protocol):
    def eligible_sources(self, question, sources): ...
    def verify(self, question, answer, sources): ...


class EmbeddingModel(Protocol):
    @property
    def spec(self): ...
    def embed(self, text): ...
